def canonical_signature_fingerprint(signature):
    _, canonical = native_function_pointer_type(signature)
    canonical = re.sub(r"\s*\*\s*", "*", canonical)
    canonical = re.sub(r"\s+", " ", canonical).strip()
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def render_adapter_entries(functions, versions):
    native = [
        "// Generated rows; consume with PLUMED_MPIW_NATIVE_FUNCTION(name, id, version, argc)."
    ]
    thread = [
        "// Generated macro rows; consume with PLUMED_MPIW_THREAD_MPI_FUNCTION(name, symbol)."
    ]
    identifiers = {}
    for function in functions:
        name = function["name"]
        identifier = int(hashlib.sha256(name.encode("ascii")).hexdigest()[:8], 16)
        if identifier in identifiers:
            raise ValueError(
                f"signature identifier collision: {name} and {identifiers[identifier]}"
            )
        identifiers[identifier] = name
        route = function.get("provider_routes", {}).get("internal_thread_mpi", {})
        version = versions[name]
        argc = len(parse_signature(function["signature"])[2])
        injected = function.get("provider_routes", {}).get("injected_real_mpi", {})
        if injected.get("status") != "unavailable":
            native.append(
                f"PLUMED_MPIW_NATIVE_FUNCTION({name}, 0x{identifier:08x}, {version}, {argc})"
            )
        if route.get("status") in {"direct", "emulated"} and route.get("symbol"):
            thread.append(f"PLUMED_MPIW_THREAD_MPI_FUNCTION({name}, {route['symbol']})")
    return "\n".join(native) + "\n", "\n".join(thread) + "\n"


