def render_native_adapter_body(functions, constants, versions, availability):
    template = (DEVELOPMENT / "native-adapter.c.in").read_text()
    implemented = [
        function
        for function in functions
        if function.get("native_adapter") == "implemented"
    ]
    manual = set(
        re.findall(r"static [^\n]+ plumed_mpiw_(MPI_[A-Za-z0-9_]+)\(", template)
    )
    generated_functions = []
    for function in implemented:
        name = function["name"]
        route = function.get("provider_routes", {}).get("injected_real_mpi", {})
        if route.get("status") == "unavailable" or function.get("callbacks"):
            raise ValueError(
                f"{name}: native adapter cannot publish unavailable/callback function"
            )
        if name not in manual:
            gromacs_names = set(availability["gromacs_thread_mpi_functions"])
            route_symbol = (
                function.get("provider_routes", {})
                .get("internal_thread_mpi", {})
                .get("symbol")
            )
            if name in gromacs_names and route_symbol:
                generated_functions.append(
                    render_native_adapter_function_with_gromacs_binding(
                        function, route_symbol
                    )
                )
            else:
                generated_functions.append(render_native_adapter_function(function))

    def guard(name, kind):
        return _native_availability_guard(name, availability, kind)

    function_rows = [
        "#define PLUMED_MPIW_ENTRY(name, id, version, argc, fn) { (uint32_t)sizeof(plumed_mpiw_function_entry), #name, id, version, argc, (plumed_mpiw_generic_fn)(fn) }",
        "/* Rows append contiguously in declaration order, including conditional rows. The identifier is metadata only; it is never an array index or byte offset. */",
        "static const plumed_mpiw_function_entry plumed_mpiw_functions[] = {",
    ]
    for index, function in enumerate(implemented):
        name = function["name"]
        route = function.get("provider_routes", {}).get("injected_real_mpi", {})
        if route.get("status") == "unavailable" or function.get("callbacks"):
            raise ValueError(
                f"{name}: native adapter cannot publish unavailable/callback function"
            )
        identifier = int(hashlib.sha256(name.encode("ascii")).hexdigest()[:8], 16)
        _, _, raw_args = parse_signature(function["signature"])
        function_rows += [
            guard(name, "function"),
            f"  PLUMED_MPIW_ENTRY({name}, 0x{identifier:08x}u, {versions[name]}u, {len(raw_args)}u, plumed_mpiw_{name}),",
            "#endif",
        ]
    function_rows += ["};", "#undef PLUMED_MPIW_ENTRY"]

    implemented_constants = [
        constant
        for constant in constants
        if constant.get("native_adapter") == "implemented"
    ]
    gromacs_constants = set(availability["gromacs_thread_mpi_constants"])

    def tmpi_constant_expression(binding):
        # GROMACS exposes the upstream tMPI API in the global namespace.
        return binding

    def tmpi_provider_expression(provider, name):
        if provider.get("status") == "stable-tmpi-mapped":
            binding = provider.get("binding")
            if not isinstance(binding, str) or not re.fullmatch(
                r"TMPI_[A-Z0-9_]+", binding
            ):
                raise ValueError(f"{name}: mapped tMPI constant lacks a symbol binding")
            return tmpi_constant_expression(binding)
        if (
            provider.get("status") == "stable-tmpi-reviewed-translation"
            and provider.get("binding") is None
            and provider.get("binding_expression")
            == REVIEWED_TMPI_NULL_EXPRESSIONS.get(name)
        ):
            return provider["binding_expression"]
        raise ValueError(
            f"{name}: GROMACS tMPI constant lacks a reviewed native binding"
        )

    constant_impl = []
    constant_accessors = []
    for constant in implemented_constants:
        name = constant["standard_api_name"]
        category = constant["class"]
        native_type = constant.get("native_type")
        if not native_type:
            raise ValueError(f"{name}: implemented native constant lacks native_type")
        constant_impl.append(guard(name, "constant"))
        if category == "provider_handle":
            if name in gromacs_constants:
                provider = constant.get("thread_mpi_2026_4", {})
                if name == "MPI_COMM_SELF":
                    tmpi_type = "tMPI_Comm"
                    tmpi_value = "tMPI_Get_comm_self()"
                else:
                    tmpi_type = re.sub(
                        r"\bMPI_(Comm|Datatype|Errhandler|Group|Op|Request|Status|Fint)\b",
                        r"tMPI_\1",
                        native_type,
                    )
                    tmpi_value = tmpi_provider_expression(provider, name)
                constant_impl += [
                    f"static void plumed_mpiw_value_{name}(void *out) {{",
                    "#if defined(GMX_THREAD_MPI) && GMX_THREAD_MPI",
                    f"  const {tmpi_type} value = {tmpi_value};",
                    "#else",
                    f"  const {native_type} value = {name};",
                    "#endif",
                    "  memcpy(out, &value, sizeof(value));",
                    "}",
                ]
            else:
                constant_impl.append(
                    f"PLUMED_MPIW_HANDLE_CONSTANT({name}, {native_type})"
                )
        elif name in gromacs_constants and category in {
            "provider_integer",
            "compile_time_integer",
            "buffer_sentinel",
            "status_sentinel",
            "status_array_sentinel",
        }:
            binding = constant.get("thread_mpi_2026_4", {}).get("binding")
            if not binding:
                raise ValueError(
                    f"{name}: GROMACS tMPI constant lacks a native binding"
                )
            if category in {"provider_integer", "compile_time_integer"}:
                tmpi_type = "int"
            elif category in {"status_sentinel", "status_array_sentinel"}:
                tmpi_type = "tMPI_Status *"
            else:
                tmpi_type = "void *"
            constant_impl += [
                f"static void plumed_mpiw_value_{name}(void *out) {{",
                "#if defined(GMX_THREAD_MPI) && GMX_THREAD_MPI",
                f"  const {tmpi_type} value = {tmpi_constant_expression(binding)};",
                "#else",
                f"  const {native_type} value = {name};",
                "#endif",
                "  memcpy(out, &value, sizeof(value));",
                "}",
            ]
        elif category == "provider_handle":
            constant_impl.append(f"PLUMED_MPIW_HANDLE_CONSTANT({name}, {native_type})")
        elif category in {"provider_integer", "compile_time_integer"}:
            constant_impl.append(f"PLUMED_MPIW_INTEGER_CONSTANT({name})")
        elif category in {
            "buffer_sentinel",
            "status_sentinel",
            "status_array_sentinel",
        }:
            constant_impl.append(f"PLUMED_MPIW_POINTER_CONSTANT({name})")
        else:
            raise ValueError(f"{name}: unsupported native constant class {category}")
        constant_impl.append("#endif")
        constant_accessors.append(guard(name, "constant"))
        constant_accessors.append(
            f"static const plumed_mpiw_constant_accessor_fn plumed_mpiw_accessor_{name} = &plumed_mpiw_value_{name};"
        )
        constant_accessors.append("#endif")
    constant_impl += [
        "#if defined(GMX_THREAD_MPI) && GMX_THREAD_MPI",
        "static plumed_mpiw_generic_fn plumed_mpiw_native_runtime_identity = (plumed_mpiw_generic_fn)&tMPI_Initialized;",
        "#else",
        "static plumed_mpiw_generic_fn plumed_mpiw_native_runtime_identity = (plumed_mpiw_generic_fn)&MPI_Initialized;",
        "#endif",
    ]
    constant_metadata = []
    for constant in implemented_constants:
        name = constant["standard_api_name"]
        native_type = constant["native_type"]
        if name in gromacs_constants:
            tmpi_type = re.sub(
                r"\bMPI_(Comm|Datatype|Errhandler|Group|Op|Request|Status|Fint)\b",
                r"tMPI_\1",
                native_type,
            )
            constant_metadata += [
                guard(name, "constant"),
                "#if defined(GMX_THREAD_MPI) && GMX_THREAD_MPI",
                f"  PLUMED_MPIW_VALUE({name}, {tmpi_type}),",
                "#else",
                f"  PLUMED_MPIW_VALUE({name}, {native_type}),",
                "#endif",
                "#endif",
            ]
        else:
            constant_metadata += [
                guard(name, "constant"),
                f"  PLUMED_MPIW_VALUE({name}, {native_type}),",
                "#endif",
            ]
    constant_metadata += [
        '  { (uint32_t)sizeof(plumed_mpiw_metadata_entry), PLUMED_MPIW_VALUE_OPAQUE, 0u, "identity:runtime", sizeof(plumed_mpiw_generic_fn), 0u, &plumed_mpiw_native_runtime_identity },',
        "#if defined(GMX_THREAD_MPI) && GMX_THREAD_MPI",
        '  { (uint32_t)sizeof(plumed_mpiw_metadata_entry), PLUMED_MPIW_VALUE_UTF8, 0u, "capability:intracommunicators-only", sizeof("true"), 0u, "true" },',
        "#endif",
    ]
    replacements = {
        "/* PLUMED_MPIW_GENERATED_FUNCTIONS */": "\n\n".join(generated_functions),
        "/* PLUMED_MPIW_FUNCTION_ENTRIES */": "\n".join(function_rows),
        "/* PLUMED_MPIW_CONSTANT_IMPLEMENTATIONS */": "\n".join(constant_impl),
        "/* PLUMED_MPIW_CONSTANT_ACCESSORS */": "\n".join(constant_accessors),
        "/* PLUMED_MPIW_CONSTANT_METADATA */": "\n".join(constant_metadata),
    }
    for marker, replacement in replacements.items():
        if marker not in template:
            raise ValueError(f"native adapter template missing {marker}")
        template = template.replace(marker, replacement)
    for function in implemented:
        name = function["name"]
        match = re.search(
            r"(?m)^static [^\n]*\bplumed_mpiw_" + re.escape(name) + r"\(", template
        )
        if not match:
            raise ValueError(
                f"{name}: native adapter definition not found for host guard"
            )
        brace = template.find("{", match.start())
        depth = 0
        end = None
        for position in range(brace, len(template)):
            if template[position] == "{":
                depth += 1
            elif template[position] == "}":
                depth -= 1
                if depth == 0:
                    end = position + 1
                    break
        if end is None:
            raise ValueError(f"{name}: unterminated adapter definition")
        template = (
            template[: match.start()]
            + guard(name, "function")
            + "\n"
            + template[match.start() : end]
            + "\n#endif"
            + template[end:]
        )
    marker = "/* PLUMED_MPIW_GROMACS_VERSION_GUARD */"
    if marker not in template:
        raise ValueError(f"native adapter template missing {marker}")
    return template.replace(marker, _gromacs_version_prelude(availability))


