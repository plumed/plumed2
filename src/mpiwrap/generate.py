def generate(output, write=True):
    args_doc = json.loads((DEVELOPMENT / "argument-metadata.json").read_text())
    constants_doc = json.loads((DEVELOPMENT / "constant-metadata.json").read_text())
    types_doc = json.loads((DEVELOPMENT / "type-metadata.json").read_text())
    versions_doc = json.loads((DEVELOPMENT / "signature-versions.json").read_text())
    availability = json.loads((DEVELOPMENT / "availability-metadata.json").read_text())
    with (DEVELOPMENT / "thread-mpi-api.tsv").open(newline="") as stream:
        api_rows = list(csv.DictReader(stream, delimiter="\t"))
    functions = args_doc["functions"]
    constants = constants_doc["constants"]
    validate_availability_metadata(availability, functions, constants)
    version_records = versions_doc["signature_versions"]
    names = {function["name"] for function in functions}
    if set(version_records) != names:
        raise ValueError(
            "signature-versions.json must contain exactly one record per function"
        )
    versions = {}
    for function in functions:
        name = function["name"]
        record = version_records[name]
        if (
            not isinstance(record, dict)
            or not isinstance(record.get("version"), int)
            or record["version"] < 1
        ):
            raise ValueError(f"{name}: signature version must be a positive integer")
        fingerprint = canonical_signature_fingerprint(function["signature"])
        if record.get("canonical_type_sha256") != fingerprint:
            raise ValueError(
                f"{name}: canonical signature changed; update signature version and fingerprint"
            )
        versions[name] = record["version"]
    api_symbols = {row["symbol"] for row in api_rows}
    for function in functions:
        route = function.get("provider_routes", {}).get("internal_thread_mpi", {})
        symbol = route.get("symbol")
        if route.get("status") == "direct" and symbol not in api_symbols:
            raise ValueError(
                f"{function['name']}: direct tMPI symbol {symbol} absent from stable API inventory"
            )
    abi = (DEVELOPMENT / "provider-abi.h.in").read_text()
    abi = abi.replace(
        "/* Provider ABI source template; generate.py emits the public header. */",
        "/* Generated by generate.py from the reviewed provider ABI contract. */",
    )
    native_rows, _ = render_adapter_entries(functions, versions)
    provider_constant_names, provider_constant_functions = render_provider_constants(
        constants_doc["constants"]
    )
    dispatch_bridges, dispatch_bindings = render_provider_dispatch_bridges(
        functions, versions
    )
    constant_bridges = render_provider_constant_bridges(constants_doc["constants"])
    native_body = render_native_adapter_body(
        functions, constants, versions, availability
    )
    thread_adapter = render_thread_mpi_adapter(functions, constants, versions)
    thread_adapter = (
        '// Generated by generate.py; do not edit.\n#include "mpiwrap.h"\n'
        "#if defined(__PLUMED_MPIWRAP) && defined(__PLUMED_HAS_THREAD_MPI) && !defined(__PLUMED_HAS_MPI)\n"
        + thread_adapter
        + "\n#endif\n"
    )
    files = {
        "mpiwrap.h": render_package_header(
            functions, types_doc["types"], constants, abi
        ),
        "types.h": render_types_header(),
        "mpi-types.h": render_mpi_types_header(),
        "mpi-functions.h": render_mpi_functions_header(functions, constants),
        "mpi.h": render_mpi_header(),
        "mpiwrap.cpp": fill_template(
            "mpiwrap.cpp.in",
            {
                "POINTER_DEFINITIONS": render_provider_pointer_definitions(
                    functions, constants
                ),
                "SIGNATURE_ROWS": native_rows,
                "DISPATCH_BRIDGES": dispatch_bridges,
                "CONSTANT_BRIDGES": constant_bridges,
                "DISPATCH_BINDINGS": dispatch_bindings,
                "CONSTANT_NAMES": provider_constant_names,
                "POINTER_PUBLICATION": render_provider_pointer_publish(
                    functions, constants
                ),
                "CONSTANT_FUNCTIONS": provider_constant_functions,
            },
        ),
        "tmpi.cpp": thread_adapter,
        "thread-mpi-symbol-check.cpp.in": render_thread_symbol_checks(functions),
        "native-signature-check.cpp.in": render_native_signature_checks(
            functions, availability
        ),
        "wrapper-header-check.cpp.in": render_wrapper_header_check(),
        "native-header-check.cpp.in": render_native_header_check(),
        "native-entry-check.cpp.in": render_native_entry_check(functions, availability),
        "thread-mpi-entry-check.cpp.in": render_thread_entry_check(functions),
        "support-matrix.md": render_matrix(functions, constants, types_doc["types"]),
    }
    wrapper_header = render_host_adapter_wrapper(abi, native_body)
    # Generated C/C++ files follow project style using the checked-in formatter,
    # independent of the generated output directory (including --check temp trees).
    astyle = ROOT / "astyle/astyle"
    options = ROOT / ".astyle.options"
    if not astyle.exists() or not options.is_file():
        raise RuntimeError(f"generated code formatting requires {astyle} and {options}")
    for name, text in list(files.items()):
        if pathlib.Path(name).suffix in {".h", ".cpp", ".inc"} or name.endswith(
            ".cpp.in"
        ):
            files[name] = subprocess.check_output(
                [str(astyle), f"--options={options}"], input=text.encode()
            ).decode()
    # Probe fixtures belong with regression checks, never among module sources.
    destinations = {
        (
            ROOT / "regtest/basic/rt-mpiwrap-api" / name
            if name.endswith(".cpp.in")
            else output / name
        ): text
        for name, text in files.items()
    }
    if write:
        for path, text in destinations.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        (ROOT / "src/wrapper/Plumed.h").write_text(wrapper_header)
    return destinations, wrapper_header


