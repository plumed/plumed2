def fill_template(name, sections):
    text = (DEVELOPMENT / name).read_text()
    for key, body in sections.items():
        marker = "@" + key + "@"
        if text.count(marker) != 1:
            raise ValueError(f"{name}: expected exactly one {marker}")
        text = text.replace(marker, body.rstrip())
    if re.search(r"@[A-Z_]+@", text):
        raise ValueError(f"{name}: unresolved generation marker")
    return text


