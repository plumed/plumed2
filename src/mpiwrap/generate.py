def render_provider_dispatch_bridges(functions, versions):
    """Generate the kernel-side normalized-to-native dispatcher bridges."""
    definitions = ["// Generated canonical-dispatch bridges for the typed frontend."]
    bindings = ["// Generated typed bridge publication rows."]
    for function in functions:
        result, name, raw_args = parse_signature(function["signature"])
        if not _provider_frontend_supported(function):
            continue
        args_meta = {item["name"]: item for item in function["arguments"]}
        signature_args = [provider_argument(raw) for raw in raw_args]
        lines = [
            f"static {provider_result(result)} plumed_mpiw_bridge_{name}({', '.join(signature_args) if signature_args else 'void'}) {{",
            "  Registry &registry = currentRegistry();",
        ]
        native_cells = []
        after = []
        for raw in raw_args:
            argname = name_argument(raw)
            item = args_meta[argname]
            conversion = item["conversion"]
            ctype = item["c_type"].strip()
            direction = item["direction"]
            if conversion == "scalar_value":
                native_type = native_argument_type(raw)
                local = f"native_{argname}"
                lines.append(
                    f"  {native_type} {local} = static_cast<{native_type}>({argname});"
                )
                native_cells.append(f"&{local}")
            elif conversion == "opaque_handle_value":
                handle = re.search(
                    r"MPI_(Comm|Group|Datatype|Request|Op|Errhandler)", ctype
                ).group(1)
                local = f"native_{argname}"
                lines += [
                    f'  NativeBuffer {local}(registry.nativeHandleSize("{handle}"));',
                    f"  std::memcpy({local}.data(), {argname}.bytes, {local}.size());",
                ]
                if handle == "Comm" and direction in {"in", "inout"}:
                    lines.append(
                        f'  validateInputComm(registry, "{name}", {local}.data());'
                    )
                native_cells.append(f"{local}.data()")
            elif conversion in {
                "scalar_ref",
                "buffer",
                "char_buffer",
                "pointer_storage",
                "array",
                "integer_array",
            }:
                pointer_value = argname
                if "const " in raw:
                    pointer_value = (
                        f"const_cast<void *>(static_cast<const void *>({argname}))"
                    )
                native_cells.append(pointer_value)
            elif conversion == "handle_ref":
                handle = re.search(
                    r"MPI_(Comm|Group|Datatype|Request|Op|Errhandler)", ctype
                ).group(1)
                local = f"native_{argname}"
                ptr = f"native_pointer_{argname}"
                lines.append(
                    f'  NativeBuffer {local}(registry.nativeHandleSize("{handle}"));'
                )
                if direction in {"in", "inout"}:
                    lines.append(
                        f"  if ({argname}) std::memcpy({local}.data(), {argname}->bytes, {local}.size());"
                    )
                    if handle == "Comm":
                        lines.append(
                            f'  if ({argname}) validateInputComm(registry, "{name}", {local}.data());'
                        )
                lines.append(f"  void *{ptr} = {argname} ? {local}.data() : nullptr;")
                native_cells.append(ptr)
                if direction in {"out", "inout"}:
                    after += [
                        f"  if ({argname} && valid_output) {{",
                        f"    std::memset({argname}->bytes, 0, sizeof({argname}->bytes));",
                        f"    std::memcpy({argname}->bytes, {local}.data(), {local}.size());",
                        "  }",
                    ]
            elif conversion == "handle_array":
                handle = re.search(
                    r"MPI_(Comm|Group|Datatype|Request|Op|Errhandler)", ctype
                ).group(1)
                extent = _frontend_array_extent(function, item)
                local = f"native_{argname}"
                ptr = f"native_pointer_{argname}"
                lines += [
                    f'  if ({extent} < 0) throw std::invalid_argument("{name} requires nonnegative {extent}");',
                    f'  const std::uint32_t {local}_size = registry.nativeHandleSize("{handle}");',
                    f"  NativeBuffer {local}(static_cast<std::size_t>({extent}) * {local}_size);",
                ]
                if direction in {"in", "inout"}:
                    lines.append(
                        f"  if ({argname} && {extent} > 0) for (int i = 0; i < {extent}; ++i) std::memcpy({local}.data() + static_cast<std::size_t>(i) * {local}_size, {argname}[i].bytes, {local}_size);"
                    )
                lines.append(
                    f"  void *{ptr} = {argname} && {extent} > 0 ? {local}.data() : nullptr;"
                )
                native_cells.append(ptr)
                if direction in {"out", "inout"}:
                    after += [
                        f"  if ({argname} && valid_output) for (int i = 0; i < {extent}; ++i) {{",
                        f"    std::memset({argname}[i].bytes, 0, sizeof({argname}[i].bytes));",
                        f"    std::memcpy({argname}[i].bytes, {local}.data() + static_cast<std::size_t>(i) * {local}_size, {local}_size);",
                        "  }",
                    ]
            elif conversion == "status":
                local = f"native_{argname}"
                ptr = f"native_pointer_{argname}"
                has_input = "true" if direction == "in" else "false"
                lines += [
                    f"  NativeBuffer {local}(registry.nativeStatusSize());",
                    f"  if ({argname} && {has_input}) encodeNativeStatus(registry, *{argname}, {local}.data());",
                    f"  void *{ptr} = {argname} ? {local}.data() : nativeStatusIgnore(registry);",
                ]
                native_cells.append(ptr)
                if direction in {"out", "inout"}:
                    after.append(
                        f"  if ({argname} && valid_output) decodeNativeStatus(registry, {local}.data(), {argname});"
                    )
            elif conversion == "status_array":
                extent = _frontend_array_extent(function, item)
                local = f"native_{argname}"
                ptr = f"native_pointer_{argname}"
                has_input = "true" if direction in {"in", "inout"} else "false"
                lines += [
                    f'  if ({extent} < 0) throw std::invalid_argument("{name} requires nonnegative {extent}");',
                    f"  const std::uint32_t {local}_size = registry.nativeStatusSize();",
                    f"  NativeBuffer {local}(static_cast<std::size_t>({extent}) * {local}_size);",
                    f"  if ({argname} && {extent} > 0 && {has_input}) for (int i = 0; i < {extent}; ++i) encodeNativeStatus(registry, {argname}[i], {local}.data() + static_cast<std::size_t>(i) * {local}_size);",
                    f"  void *{ptr} = {argname} && {extent} > 0 ? {local}.data() : nativeStatusesIgnore(registry);",
                ]
                native_cells.append(ptr)
                if direction in {"out", "inout"}:
                    out_count = _provider_bridge_array_output_count(function, extent)
                    after.append(
                        f"  if ({argname} && valid_output) for (int i = 0; i < {out_count}; ++i) decodeNativeStatus(registry, {local}.data() + static_cast<std::size_t>(i) * {local}_size, &{argname}[i]);"
                    )
            else:
                raise ValueError(f"{name}: unsupported bridge conversion {conversion}")

        identifier = int(hashlib.sha256(name.encode("ascii")).hexdigest()[:8], 16)
        lines += [
            f'  plumed_mpiw_generic_fn erased = registry.dispatch("{name}", 0x{identifier:08x}u, {versions[name]}u, {len(raw_args)}u);',
            f"  plumed_mpiw_transport_{name}_fn dispatch = reinterpret_cast<plumed_mpiw_transport_{name}_fn>(erased);",
            f'  if (!dispatch) unavailable("{name}");',
        ]
        if result == "void":
            lines.append(f"  dispatch({', '.join(native_cells + ['nullptr'])});")
            lines += after + ["}"]
        elif result == "int":
            lines += [
                "  std::int32_t native_return_value = 0;",
                f"  dispatch({', '.join(native_cells + ['&native_return_value'])});",
                *(
                    ["  const bool valid_output = (native_return_value == 0);"]
                    if any("valid_output" in line for line in after)
                    else []
                ),
                *after,
                "  return native_return_value;",
                "}",
            ]
        elif result in HANDLES:
            handle = result.removeprefix("MPI_")
            lines += [
                f'  NativeBuffer native_result(registry.nativeHandleSize("{handle}"));',
                f"  dispatch({', '.join(native_cells + ['native_result.data()'])});",
                "  plumed_mpiw_handle_storage result{};",
                "  std::memcpy(result.bytes, native_result.data(), native_result.size());",
                "  return result;",
                "}",
            ]
        elif result in {"float", "double", "long double", "MPI_Aint", "MPI_Count"}:
            lines += [
                f"  {result} native_result = 0;",
                f"  dispatch({', '.join(native_cells + ['&native_result'])});",
                "  return native_result;",
                "}",
            ]
        else:
            raise ValueError(f"{name}: unsupported native bridge result {result}")
        definitions += lines
        bindings.append(
            f"PLUMED_MPIW_PROVIDER_BRIDGE({name}, plumed_mpiw_bridge_{name})"
        )
    return "\n".join(definitions) + "\n", "\n".join(bindings) + "\n"


