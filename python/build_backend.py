"""PEP 517 backend that builds and stages a small Unix PLUMED runtime."""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

from setuptools import build_meta as _setuptools_backend


PYTHON_ROOT = Path(__file__).resolve().parent
RUNTIME_PACKAGE = PYTHON_ROOT / "plumed_runtime"


def _source_root() -> Path:
    staged = PYTHON_ROOT / "plumed_source"
    return staged if staged.is_dir() else PYTHON_ROOT.parent


def _copy_build_inputs(source: Path, destination: Path) -> None:
    destination.mkdir(parents=True)
    for filename in (
        "configure",
        "configure.ac",
        "Makefile",
        "Makefile.conf.in",
        "VERSION.txt",
        "COPYING.LESSER",
        "PEOPLE",
        "sourceme.sh.in",
        "stamp-h.in",
    ):
        shutil.copy2(source / filename, destination / filename)
    for dirname in ("src", "json", "scripts", "patches", "vim"):
        shutil.copytree(source / dirname, destination / dirname, symlinks=True)


def _default_modules(source: Path) -> list[str]:
    modules = []
    for module_type in sorted((source / "src").glob("*/module.type")):
        kind = module_type.read_text().strip()
        if kind in {"always", "default-on"}:
            modules.append(module_type.parent.name)
    return modules


def _run(command: list[str], *, cwd: Path, env: dict[str, str] | None = None) -> None:
    print("+", " ".join(command), flush=True)
    subprocess.run(command, cwd=cwd, env=env, check=True)


def _bundle_kernel_enabled() -> bool:
    setting = os.environ.get("PLUMED_BUILD_KERNEL")
    if setting is None and os.environ.get("plumed_default_kernel"):
        return False
    return (setting or "1").lower() not in {"0", "no", "false"}


def _embed_metadata(header: Path, metadata: bytes) -> None:
    # Keep each literal below the 65,536-byte minimum supported by C++ compilers.
    chunk_size = 32_000
    delimiter = "PLM" + hashlib.sha256(metadata).hexdigest()[:10]
    chunks = [metadata[i : i + chunk_size] for i in range(0, len(metadata), chunk_size)]
    lines = [
        "// Generated by python/build_backend.py; do not edit.\n",
        f"static constexpr std::size_t inputBuilderMetadataJSONSize = {len(metadata)};\n",
        f"static constexpr std::size_t inputBuilderMetadataJSONChunkSize = {chunk_size};\n",
        f"static constexpr char inputBuilderMetadataJSONChunks[{max(1, len(chunks))}][{chunk_size + 1}] = {{\n",
    ]
    for chunk in chunks:
        text = chunk.decode("utf-8")
        while f'){delimiter}"' in text:
            delimiter += "X"
        lines.append(f'R"{delimiter}({text}){delimiter}",\n')
    if not chunks:
        lines.append('"",\n')
    lines.append("};\n")
    header.write_text("".join(lines), encoding="utf-8")


def _runtime_environment(source: Path) -> dict[str, str]:
    env = os.environ.copy()
    library_dir = str(source / "src" / "lib")
    loader_var = "DYLD_LIBRARY_PATH" if sys.platform == "darwin" else "LD_LIBRARY_PATH"
    env[loader_var] = library_dir + os.pathsep + env.get(loader_var, "")
    env["PLUMED_PREPEND_PATH"] = library_dir
    env["PLUMED_ROOT"] = str(source)
    return env


def _copy_runtime(source: Path, modules: list[str]) -> None:
    suffix = "dylib" if sys.platform == "darwin" else "so"
    library_dir = source / "src" / "lib"
    runtime_lib = RUNTIME_PACKAGE / "lib"
    runtime_bin = RUNTIME_PACKAGE / "bin"
    runtime_root = RUNTIME_PACKAGE / "share" / "plumed"
    for path in (runtime_lib, runtime_bin, runtime_root):
        shutil.rmtree(path, ignore_errors=True)
        path.mkdir(parents=True)

    for name in (f"libplumedKernel.{suffix}", f"libplumed.{suffix}"):
        candidate = library_dir / name
        if not candidate.is_file():
            raise RuntimeError(f"PLUMED build did not produce {candidate}")
        shutil.copy2(candidate, runtime_lib / name)
    executable = library_dir / "plumed"
    if not executable.is_file():
        raise RuntimeError("PLUMED build did not produce src/lib/plumed")
    shutil.copy2(executable, runtime_bin / "plumed")
    (runtime_bin / "plumed").chmod(0o755)

    for dirname in ("scripts", "patches", "vim"):
        shutil.copytree(source / dirname, runtime_root / dirname)
    for relative in (
        Path("src/include"),
        Path("src/config/config.txt"),
        Path("src/config/compile_options.sh"),
        Path("src/colvar/Template.cpp"),
    ):
        origin = source / relative
        target = runtime_root / relative
        if origin.is_dir():
            shutil.copytree(origin, target, symlinks=True)
        elif origin.is_file():
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(origin, target)

    license_dir = RUNTIME_PACKAGE / "licenses"
    license_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source / "COPYING.LESSER", license_dir / "COPYING.LESSER")
    build_info = [
        f"PLUMED version: {(source / 'VERSION.txt').read_text().strip()}",
        "Build system: configure/make",
        "Shared kernel: enabled",
        "MPI: disabled",
        "OpenMP: disabled",
        "External BLAS/LAPACK: disabled",
        "External FFTW: disabled",
        "Enabled modules: " + ", ".join(modules),
    ]
    (runtime_root / "build-info.txt").write_text("\n".join(build_info) + "\n")

    if sys.platform == "darwin":
        _fix_macos_load_paths(runtime_lib, runtime_bin)


def _fix_macos_load_paths(runtime_lib: Path, runtime_bin: Path) -> None:
    kernel = runtime_lib / "libplumedKernel.dylib"
    wrapper = runtime_lib / "libplumed.dylib"
    executable = runtime_bin / "plumed"
    _run(
        ["install_name_tool", "-id", "@rpath/libplumedKernel.dylib", str(kernel)],
        cwd=runtime_lib,
    )
    _run(
        ["install_name_tool", "-id", "@rpath/libplumed.dylib", str(wrapper)],
        cwd=runtime_lib,
    )
    for binary in (wrapper, executable):
        dependencies = subprocess.check_output(["otool", "-L", str(binary)], text=True)
        for line in dependencies.splitlines()[1:]:
            dependency = line.strip().split(" ", 1)[0]
            if dependency.endswith("/libplumedKernel.dylib"):
                _run(
                    [
                        "install_name_tool",
                        "-change",
                        dependency,
                        "@rpath/libplumedKernel.dylib",
                        str(binary),
                    ],
                    cwd=runtime_lib,
                )
            elif dependency.endswith("/libplumed.dylib"):
                _run(
                    [
                        "install_name_tool",
                        "-change",
                        dependency,
                        "@rpath/libplumed.dylib",
                        str(binary),
                    ],
                    cwd=runtime_lib,
                )
        _run(
            [
                "install_name_tool",
                "-add_rpath",
                "@loader_path/../lib" if binary == executable else "@loader_path",
                str(binary),
            ],
            cwd=runtime_lib,
        )


def _build_runtime() -> None:
    if sys.platform not in {"linux", "darwin"}:
        raise RuntimeError(
            "Bundled PLUMED kernels are currently supported on Linux and macOS only"
        )
    source_root = _source_root()
    modules = _default_modules(source_root)
    if not modules:
        raise RuntimeError("No always or default-on PLUMED modules were found")

    with tempfile.TemporaryDirectory(prefix="plumed-wheel-build-") as temporary:
        source = Path(temporary) / "plumed"
        _copy_build_inputs(source_root, source)
        prefix = "/plumed_runtime"
        module_option = "--enable-modules=none:" + ":".join(
            "+" + name for name in modules
        )
        configure = [
            "./configure",
            f"--prefix={prefix}",
            module_option,
            "--enable-shared",
            "--disable-static-archive",
            "--disable-static-patch",
            "--disable-python",
            "--disable-doc",
            "--disable-mpi",
            "--disable-openmp",
            "--disable-external-blas",
            "--disable-external-lapack",
            "--disable-fftw",
            "--disable-molfile-plugins",
            "--disable-external-molfile-plugins",
            "--disable-zlib",
            "--disable-rpath",
            "CXXFLAGS="
            + (os.environ.get("CXXFLAGS", "") + " -O2 -D__PLUMED_PIP_BUNDLE").strip(),
            "CFLAGS=" + (os.environ.get("CFLAGS", "") + " -O2").strip(),
        ]
        if sys.platform == "darwin":
            configure.append("--disable-absolute-install-name")
        _run(configure, cwd=source)
        jobs = str(max(1, min(4, os.cpu_count() or 1)))
        # The runtime executable is installed under bin/ and its bundled libraries
        # under lib/. A relative run path lets auditwheel resolve the kernel inside
        # the wheel, and remains valid after installation at any prefix.
        link_env = os.environ.copy()
        link_env["LD_RUN_PATH"] = "$ORIGIN/../lib"
        _run(["make", "-C", "src/config"], cwd=source, env=link_env)
        _run(["make", "-C", "src/lib", "-j" + jobs], cwd=source, env=link_env)

        action_list = source / "json" / "action_list"
        with action_list.open("w", encoding="utf-8") as output:
            subprocess.run(
                ["bash", "get_action_list.sh"],
                cwd=source / "json",
                stdout=output,
                check=True,
            )
        metadata = source / "json" / "syntax.json"
        with metadata.open("wb") as output:
            subprocess.run(
                [
                    str(source / "src/lib/plumed"),
                    "--no-mpi",
                    "gen_json",
                    "--actions",
                    str(action_list),
                ],
                cwd=source / "json",
                env=_runtime_environment(source),
                stdout=output,
                check=True,
            )
        parsed = json.loads(metadata.read_text(encoding="utf-8"))
        if not any(
            isinstance(value, dict) and "syntax" in value for value in parsed.values()
        ):
            raise RuntimeError("The built PLUMED kernel exported no action metadata")
        _embed_metadata(
            source / "src/core/InputBuilderMetadata.inc", metadata.read_bytes()
        )
        (source / "src/core/PlumedMain.o").unlink(missing_ok=True)
        _run(["make", "-C", "src/lib", "-j" + jobs], cwd=source)
        _copy_runtime(source, modules)


def _copy_sdist_source(destination: Path) -> None:
    source = PYTHON_ROOT.parent
    destination.mkdir(parents=True)
    for filename in (
        "configure",
        "configure.ac",
        "Makefile",
        "Makefile.conf.in",
        "VERSION.txt",
        "COPYING.LESSER",
        "PEOPLE",
        "sourceme.sh.in",
        "stamp-h.in",
    ):
        shutil.copy2(source / filename, destination / filename)
    for dirname in ("src", "json", "scripts", "patches", "vim"):
        shutil.copytree(
            source / dirname,
            destination / dirname,
            symlinks=True,
            ignore=shutil.ignore_patterns("*.o", "*.d", "*.on", "*.off"),
        )


def build_sdist(sdist_directory, config_settings=None):
    staged = PYTHON_ROOT / "plumed_source"
    created = not staged.exists()
    try:
        if created:
            _copy_sdist_source(staged)
        os.environ["plumed_force_cython"] = "yes"
        return _setuptools_backend.build_sdist(sdist_directory, config_settings)
    finally:
        if created:
            shutil.rmtree(staged, ignore_errors=True)


def build_wheel(wheel_directory, config_settings=None, metadata_directory=None):
    kernel_setting = os.environ.get("PLUMED_BUILD_KERNEL")
    force_cython_setting = os.environ.get("plumed_force_cython")
    # PLUMED's in-tree install passes plumed_default_kernel when building the
    # traditional wrapper-only interface from a staged python/ directory.
    bundle_kernel = _bundle_kernel_enabled()
    if kernel_setting is None and not bundle_kernel:
        os.environ["PLUMED_BUILD_KERNEL"] = "0"
    if bundle_kernel and force_cython_setting is None:
        os.environ["plumed_force_cython"] = "yes"
    try:
        if bundle_kernel:
            _build_runtime()
        return _setuptools_backend.build_wheel(
            wheel_directory, config_settings, metadata_directory
        )
    finally:
        if kernel_setting is None:
            os.environ.pop("PLUMED_BUILD_KERNEL", None)
        if force_cython_setting is None:
            os.environ.pop("plumed_force_cython", None)
        for name in ("lib", "bin", "share", "licenses"):
            path = RUNTIME_PACKAGE / name
            if path.is_dir():
                shutil.rmtree(path, ignore_errors=True)
            elif path.exists():
                path.unlink()


