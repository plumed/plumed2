#!/usr/bin/env python3
"""Generate explicit conda outputs (conda-build cannot index looped outputs)."""

import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
catalog = json.loads((root / "extensions/catalog.json").read_text())
modules = [
    name
    for name, module in catalog["modules"].items()
    if module["type"] == "default-off" and not module["required_features"]
]
header = """# Generated by extensions/conda_recipe.py. Edit the generator or catalog.
{% set version = environ['VERSION'] %}
{% set base_pin = pin_compatible('plumed', exact=True).split() %}
{% set base_build = base_pin[2] if base_pin|length > 2 else 'unresolved' %}

package:
  name: plumed-extensions
  version: {{ version }}

source:
  path: ../..

build:
  number: 0
  skip: true  # [win]

requirements:
  build:
    - {{ compiler('c') }}
    - {{ compiler('cxx') }}
    - make
    - python
  host:
    - plumed {{ version }}

outputs:
"""
outputs = []
for name in modules:
    output = f"""  - name: plumed-ext-{name}
    build:
      string: base_{{{{ base_build }}}}_0
      files:
        - lib/libplumed-ext-{name}.*
        - lib/plumed/plugins/{name}.plumed
    requirements:
      host:
        - plumed {{{{ version }}}}
      run:
        - {{{{ pin_compatible('plumed', exact=True) }}}}
"""
    for dependency in catalog["modules"][name]["source_use"]:
        if dependency in modules:
            output += f"        - {{{{ pin_subpackage('plumed-ext-{dependency}', exact=True) }}}}\n"
    output += f"""    test:
      commands:
        - plumed config -q module {name}
        - PLUMED_AUTOLOAD=0 plumed --load-module={name} config -q module {name}
"""
    outputs.append(output)
footer = """
about:
  home: https://www.plumed.org/
  license: LGPL-3.0
  license_file: COPYING.LESSER
  summary: Optional PLUMED modules, built against one exact MPI-independent base
"""
(root / "conda/plumed-extensions/meta.yaml").write_text(
    header + "\n".join(outputs) + footer
)
