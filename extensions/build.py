#!/usr/bin/env python3
"""Build optional modules with the installed base's compiler and ABI settings."""

import hashlib
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from conda_config import build_environment, supported
from features import FeatureProbes, dependency_identity, feature_identity
from inventory import generate_catalog
from symbols import module_symbol

root = Path(__file__).resolve().parent.parent
config = {}
for line in (root / "Makefile.conf").read_text().splitlines():
    match = re.match(r"^(\w+)=(.*)$", line)
    if match:
        config[match[1]] = match[2]
base = Path(config["EXTENSION_BASE"])
prefix = Path(config["EXTENSION_PREFIX"])
build_id = config["EXTENSION_BUILD_ID"]
selected = config["EXTENSION_MODULES"].split()
catalog = generate_catalog()
work = root / "_extensions"
work.mkdir(exist_ok=True)
environment = dict(os.environ, PLUMED_AUTOLOAD="0")
builtin = set(
    subprocess.check_output(
        [str(base / "bin/plumed"), "--list-modules"], env=environment, text=True
    ).split()
)
current_id = subprocess.check_output(
    [str(base / "bin/plumed"), "--module-build-id"], env=environment, text=True
).strip()
if current_id != build_id:
    raise SystemExit("The installed base changed: configure the extensions again")
soext = config["SOEXT"]

# Installed kernel headers are immutable, but an installed older extension must
# not hide the source headers of another extension being rebuilt in this tree.
module_headers = work / ("headers-" + build_id)
module_headers.mkdir(exist_ok=True)
for module in catalog["modules"]:
    if module in builtin:
        continue
    link = module_headers / module
    target = root / "src" / module
    if link.is_symlink() and link.resolve() != target.resolve():
        link.unlink()
    if not link.exists():
        link.symlink_to(target, target_is_directory=True)


# Preserve literal quotes in -D flags: make passes these through a shell once.
def flags(key):
    return shlex.split(config.get(key, ""))


# PACKAGE_STRING is informational and contains escaped spaces; all ABI feature
# macros and compiler flags are preserved without running shell expansions.
cppflags = [word for word in flags("CPPFLAGS") if not word.startswith("-DPACKAGE_")]
compiler = shlex.split(os.environ.get("CXX", "")) or flags("CXX")
cxxflags = shlex.split(os.environ.get("CXXFLAGS", "")) or flags("CXXFLAGS")
if not any(flag.startswith("-std=") for flag in cxxflags):
    cxxflags.append("-std=c++17")
if "-fPIC" not in cxxflags:
    cxxflags.append("-fPIC")
linker = [*compiler, *flags("LDSHARED")[len(flags("CXX")) :]]
# Runtime flags generated by parallel code belong to the extension itself.
# The kernel's private native libraries do not: importing all of them also
# requires development symlinks absent from a runtime-only base installation.
runtime_flags = [
    flag
    for flag in cxxflags
    if flag.startswith(
        ("-fopenmp", "-qopenmp", "-fiopenmp", "-openmp", "-mp", "-pthread", "-stdlib=")
    )
]
cppflags += shlex.split(os.environ.get("CPPFLAGS", ""))
base_kernel = base / "lib" / f"libplumedKernel.{soext}"


# USE describes source dependencies. Of these, only omitted modules are separate
# libraries. No shortcut/action dependency inference is performed.
def dependencies(name):
    text = (root / "src" / name / "Makefile").read_text()
    match = re.search(r"^USE\s*[:?+]?=([^\n]*)", text, re.MULTILINE)
    return [
        dep
        for dep in (match[1].split() if match else [])
        if dep not in builtin and (root / "src" / dep / "module.type").exists()
    ]


order = []
visiting = set()


def visit(name):
    if name in order:
        return
    if name in visiting:
        raise SystemExit(f"cyclic module dependency: {name}")
    visiting.add(name)
    for dep in dependencies(name):
        visit(dep)
    visiting.remove(name)
    order.append(name)


conda_build = os.environ.get("PLUMED_CONDA_BUILD") == "1"


def available(name):
    return supported(catalog["modules"][name]["conda"]) and all(
        available(dep) for dep in dependencies(name)
    )


for module in selected:
    if conda_build and not available(module):
        print(
            f"Skipping {module}: unsupported conda target or hard dependency",
            flush=True,
        )
        continue
    visit(module)


def run(command):
    print(shlex.join(map(str, command)), flush=True)
    subprocess.run(list(map(str, command)), check=True)


header_hash = hashlib.sha256()
for header in sorted((root / "src").rglob("*")):
    if not header.is_file() or header.suffix not in (".h", ".hpp", ".inl", ".tpp"):
        continue
    header_hash.update(str(header.relative_to(root / "src")).encode())
    header_hash.update(header.read_bytes())
# Native headers/ABI can change independently of the immutable base package.
for metadata in sorted((base / "conda-meta").glob("*.json")):
    header_hash.update(metadata.read_bytes())
headers = header_hash.hexdigest()


def compile_source(task):
    command, source, obj = task
    signature = hashlib.sha256(
        (json.dumps(list(map(str, command))) + headers + build_id).encode()
        + source.read_bytes()
    ).hexdigest()
    stamp = obj.with_suffix(".signature")
    if obj.exists() and stamp.exists() and stamp.read_text() == signature:
        return
    run(command)
    stamp.write_text(signature)


numeric_symbols = {}
for component in ("blas", "lapack"):
    header = (root / "src" / component / (component + ".h")).read_text()
    numeric_symbols[component] = set(
        re.findall(r"PLUMED_BLAS_F77_FUNC\(\s*([a-z0-9_]+)\s*,", header)
    )

native_report = {}
probes = FeatureProbes(
    compiler, cppflags, cxxflags, flags("LDFLAGS"), base, work / "probes"
)


def numeric_link_flags(objects):
    # Public inline matrix helpers can emit native BLAS/LAPACK calls even when
    # the module itself has no feature guards. Inspect actual imports, keeping
    # this independent of shortcut/action dependencies.
    nm = shlex.split(os.environ.get("NM", "nm"))
    output = subprocess.check_output([*nm, "-u", *map(str, objects)], text=True)
    undefined = {
        line.split()[-1].split("@", 1)[0].strip("_").lower()
        for line in output.splitlines()
        if line.split()
    }
    needed = {
        component: sorted(undefined & names)
        for component, names in numeric_symbols.items()
    }
    selected = []
    if any(needed.values()):
        dynamic = flags("DYNAMIC_LIBS")
        for index, flag in enumerate(dynamic):
            lower = flag.lower()
            provider = any(
                name in lower
                for name in ("openblas", "mkl", "atlas", "blis", "accelerate", "veclib")
            )
            direct = any(
                needed[component] and component in lower for component in needed
            )
            if flag.startswith("-L") or (
                (flag.startswith("-l") or Path(flag).is_absolute())
                and (provider or direct)
            ):
                selected.append(flag)
            elif (
                flag == "-framework"
                and index + 1 < len(dynamic)
                and dynamic[index + 1] == "Accelerate"
            ):
                selected.extend([flag, "Accelerate"])
    return selected, needed


for name in order:
    directory = work / name
    directory.mkdir(exist_ok=True)
    sources = sorted((root / "src" / name).glob("*.cpp"))
    identity = directory / "module_identity.cpp"
    policy = catalog["modules"][name]["conda"] if conda_build else {}
    module_env = build_environment(
        policy, dict(os.environ, CPPFLAGS="", CXXFLAGS="", LDFLAGS="")
    )
    module_cppflags = cppflags + shlex.split(module_env.get("CPPFLAGS", ""))
    module_cxxflags = cxxflags + shlex.split(module_env.get("CXXFLAGS", ""))
    module_ldflags = flags("LDFLAGS") + shlex.split(module_env.get("LDFLAGS", ""))
    module_probes = probes
    if any(policy.get(key) for key in ("cppflags", "cxxflags", "ldflags")):
        module_probes = FeatureProbes(
            compiler,
            module_cppflags,
            module_cxxflags,
            module_ldflags,
            base,
            work / "probes" / name,
        )
    try:
        feature_flags, native_flags, enabled_features = module_probes.module_flags(
            catalog["modules"][name]["feature_guards"],
            policy.get("required_features", []),
            policy.get("optional_features", []),
            policy.get("disabled_features", []),
        )
    except ValueError as error:
        raise SystemExit(f"{name}: {error}") from error
    identity.write_text(
        '#include "config/Config.h"\n'
        + f'extern "C" const char* {module_symbol(name)}() {{ return "{build_id}"; }}\n'
        + f'extern "C" const void* {module_symbol(name)}_kernel() {{ return reinterpret_cast<const void*>(&PLMD::config::getModuleBuildID); }}\n'
        + dependency_identity(name, dependencies(name))
        + feature_identity(
            name,
            re.findall(
                r"-D__PLUMED_HAS_([A-Z0-9_]+)",
                " ".join([*module_cppflags, *module_cxxflags, *feature_flags]),
            ),
        )
    )
    objects = []
    tasks = []
    for source in [*sources, identity]:
        obj = directory / (source.stem + ".o")
        objects.append(obj)
        # The installed base and its headers are immutable for this build ID.
        # Included module headers can change locally, so never reuse objects
        # solely based on the translation unit's timestamp.
        tasks.append(
            (
                [
                    *compiler,
                    *module_cppflags,
                    *module_cxxflags,
                    *feature_flags,
                    "-I" + str(module_headers),
                    "-I" + str(base / "include/plumed"),
                    "-I" + str(root / "src"),
                    f'-DPLUMED_MODULE_DIR="{name}/"',
                    "-c",
                    source,
                    "-o",
                    obj,
                ],
                source,
                obj,
            )
        )
    with ThreadPoolExecutor(max_workers=int(os.environ.get("CPU_COUNT", "8"))) as pool:
        list(pool.map(compile_source, tasks))
    library = work / f"libplumed-ext-{name}.{soext}"
    dependencies_libs = [
        work / f"libplumed-ext-{dep}.{soext}" for dep in dependencies(name)
    ]
    if soext == "dylib":
        search = [
            "-Wl,-install_name,@rpath/" + library.name,
            "-Wl,-rpath,@loader_path",
            "-Wl,-rpath," + str(base / "lib"),
        ]
    else:
        search = [
            "-Wl,-soname," + library.name,
            "-Wl,-rpath,$ORIGIN",
            "-Wl,-rpath," + str(base / "lib"),
            "-Wl,-z,defs",
        ]
    numeric_flags, imported_numeric = numeric_link_flags(objects)
    native_report[name] = {
        "module": name,
        "base_build": build_id,
        "numeric_imports": imported_numeric,
        "native_link_flags": native_flags + numeric_flags,
        "hard_modules": dependencies(name),
        "optional_features": enabled_features,
        "feature_macros": [
            "__PLUMED_HAS_" + feature
            for feature, enabled in enabled_features.items()
            if enabled
        ]
        + [
            "__PLUMED_HAS_EXTERNAL_" + component.upper()
            for component, symbols in imported_numeric.items()
            if symbols
        ],
    }
    run(
        [
            *linker,
            *module_ldflags,
            *search,
            "-L" + str(base / "lib"),
            "-o",
            library,
            *objects,
            *dependencies_libs,
            base_kernel,
            *runtime_flags,
            *[
                flag
                for flag in module_cxxflags
                if flag.startswith(
                    (
                        "-fopenmp",
                        "-qopenmp",
                        "-fiopenmp",
                        "-openmp",
                        "-mp",
                        "-pthread",
                        "-stdlib=",
                    )
                )
                and flag not in runtime_flags
            ],
            *native_flags,
            *numeric_flags,
        ]
    )
    if soext == "dylib":
        kernel_id = (
            subprocess.check_output(["otool", "-D", str(base_kernel)], text=True)
            .splitlines()[1]
            .strip()
        )
        run(
            [
                "install_name_tool",
                "-change",
                kernel_id,
                "@rpath/" + base_kernel.name,
                library,
            ]
        )
    registration = work / f"{name}.plumed"
    registration.write_text(
        f"module {name}\nbuild {build_id}\nlibrary ../../{library.name}\n"
        + "requires "
        + " ".join(dependencies(name))
        + "\n"
    )
    metadata = work / f"{name}.json"
    installed_report = dict(native_report[name])
    installed_report.pop("native_link_flags")
    installed_report["native_libraries"] = [
        flag[2:] for flag in native_flags + numeric_flags if flag.startswith("-l")
    ]
    metadata.write_text(json.dumps(installed_report, indent=2) + "\n")
    if sys.argv[1] == "install":
        (prefix / "lib/plumed/plugins").mkdir(parents=True, exist_ok=True)
        include_root = prefix / "include/plumed"
        for header in (root / "src" / name).rglob("*"):
            if not header.is_file() or header.suffix not in (
                ".h",
                ".hpp",
                ".inl",
                ".tpp",
            ):
                continue
            relative = header.relative_to(root / "src")
            destination = include_root / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            text = header.read_text()

            # Match ordinary installed headers: module-qualified includes are
            # relative to this header, independent of the caller's include path.
            def installed_include(
                match, include_root=include_root, destination=destination
            ):
                module, rest = match.groups()
                if module not in catalog["modules"]:
                    return match[0]
                target = os.path.relpath(include_root / module, destination.parent)
                return '#include "' + target + "/" + rest

            text = re.sub(
                r'^#\s*include\s*"([^/"\n]+)/([^"\n]+)',
                installed_include,
                text,
                flags=re.MULTILINE,
            )
            destination.write_text(text)
        shutil.copy2(metadata, prefix / "lib/plumed/plugins" / metadata.name)
        shutil.copy2(library, prefix / "lib" / library.name)
        shutil.copy2(registration, prefix / "lib/plumed/plugins" / registration.name)
(work / "modules.json").write_text(json.dumps(order, indent=2) + "\n")

(work / "native-dependencies.json").write_text(
    json.dumps(native_report, indent=2) + "\n"
)
