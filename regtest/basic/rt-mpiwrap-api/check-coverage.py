#!/usr/bin/env python3
"""Verify every mapped function has a semantic scenario or an explicit owner."""
import argparse
import json
from pathlib import Path
import re
import sys


def generated_unavailable(functions):
    lines = ["// Generated by check-coverage.py --write; do not edit.",
             "void check_unavailable() {", "#if !defined(__PLUMED_HAS_MPI)"]
    for function in functions:
        name = function["name"]
        args = []
        declarations = []
        for argument in function["arguments"]:
            kind = argument["c_type"]
            if kind == "...":
                continue
            variable = "argument_" + str(len(args))
            if "_function" in kind or "User_function" in kind:
                args.append("nullptr")
            elif "[3]" in kind:
                declarations.append("      int " + variable + "[1][3] {};")
                args.append(variable)
            elif "[" in kind:
                base = kind.replace("const ", "").split("[")[0].strip()
                declarations.append("      " + base + " " + variable + "[1] {};")
                args.append(variable)
            elif "*" in kind:
                base = kind.replace("const ", "").rstrip(" *")
                levels = kind.count("*")
                if base == "void":
                    declarations.append("      char " + variable + "[1] {};")
                    args.append(variable)
                else:
                    declarations.append("      " + base + " " + "*" * (levels - 1) + variable + "{};")
                    args.append("&" + variable)
            elif kind.startswith("MPI_"):
                args.append(kind + "{}")
            else:
                args.append("0")
        lines += ["  if(!mpiwrap::has_" + name[4:] + "()) {",
                  "    bool threw=false;", "    try {"] + declarations + [
                  "      (void)" + name + "(" + ",".join(args) + ");",
                  "    } catch(const std::runtime_error &error) {",
                  "      CHECK(std::string(error.what()).find(\"" + name + "\")!=std::string::npos);",
                  "      threw=true;", "    }", "    CHECK(threw);", "  }"]
    lines += ["#endif", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate unavailable-call checks")
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    root = here.parents[2]
    functions = json.loads((root / "src/mpiwrap/argument-metadata.json").read_text())["functions"]
    names = {entry["name"] for entry in functions}
    source = (here / "main.cpp").read_text()
    # Only actual invocations count: comments cannot satisfy coverage.
    source = re.sub(r"/\*.*?\*/|//[^\n]*", "", source, flags=re.S)
    calls = {"MPI_" + entry for entry in re.findall(r"\bCALL\(\s*(\w+)\s*[,)]", source)}
    calls.update(re.findall(r"\b(MPI_\w+)\s*\(", source))
    calls &= names
    owners = json.loads((here / "lifecycle-coverage.json").read_text())
    missing = names - calls - owners.keys()
    obsolete = owners.keys() - names
    if missing or obsolete:
        print("Uncovered mapped functions:", sorted(missing), "obsolete owners:", sorted(obsolete), file=sys.stderr)
        return 1
    contract = json.loads((here / "thread-mpi-contract.json").read_text())
    if set(contract) - names or len(contract) != len(set(contract)):
        print("Invalid thread-MPI capability contract", file=sys.stderr)
        return 1
    contract_lines = ["// Generated by check-coverage.py --write; do not edit.",
                      "void check_thread_mpi_contract() {",
                      "#if !defined(__PLUMED_HAS_MPI)"]
    for name in sorted(names):
        contract_lines.append("  CHECK(mpiwrap::has_" + name[4:] + "()==" +
                              ("true" if name in contract else "false") + ");")
    contract_lines += ["#endif", "}", ""]
    contract_expected = "\n".join(contract_lines)
    contract_target = here / "thread-mpi-contract.inc"
    if args.write:
        contract_target.write_text(contract_expected)
    elif not contract_target.exists() or contract_target.read_text() != contract_expected:
        print("Run check-coverage.py --write after reviewing capability contract", file=sys.stderr)
        return 1
    expected = generated_unavailable(functions)
    target = here / "unavailable.inc"
    if args.write:
        target.write_text(expected)
    elif not target.exists() or target.read_text() != expected:
        print("Run check-coverage.py --write after reviewing mapping changes", file=sys.stderr)
        return 1
    print("Mapped API coverage: %d scenarios, %d explicit lifecycle/destructive owners" % (len(calls - owners.keys()), len(owners)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
